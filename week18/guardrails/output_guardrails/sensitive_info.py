"""
Sensitive Information Detector for Output Guardrails.
Checks generated responses for:
- PII leakage (accidental disclosure of emails, phones, SSNs, financial accounts)
- Internal secret leakage (API keys, tokens, system secrets, server paths)
"""
import re
from typing import Dict, List
from guardrails.models import ActionTaken, GuardrailResult
from guardrails.input_guardrails.pii_detector import PIIDetector


class SensitiveInformationDetector:
    """
    Detection Approach:
    - Re-applies high-precision PII detection to intercept model hallucinations of personal records.
    - Scans for proprietary system secret signatures (API keys, Bearer tokens, JWT headers, private keys).
    - Checks for inadvertent leakage of system prompt instructions or internal credentials.

    Action Taken:
    - REDACT: Masks identified PII tokens and API credentials before sending the payload to user.
    - SAFE_FALLBACK: If systemic leakage or private keys are detected, the response is replaced entirely
      with a security safe fallback message.

    Limitations:
    - Synthetic but realistic PII strings generated by the model might pass without context cues.
    - Obfuscated secrets (e.g. hex-encoded or split variables) require specialized AST or entropy analyzers.
    """

    SECRET_PATTERNS = {
        "OPENAI_KEY": re.compile(r"sk-[a-zA-Z0-9]{20,T3BlbkFJ[a-zA-Z0-9]{20,}"),
        "GENERIC_API_KEY": re.compile(r"\b(?:api[_-]?key|secret[_-]?token)\s*[:=]\s*['\"]?([a-zA-Z0-9_\-]{16,})['\"]?", re.IGNORECASE),
        "BEARER_TOKEN": re.compile(r"\bBearer\s+[a-zA-Z0-9\-_.]+\.[a-zA-Z0-9\-_.]+\b", re.IGNORECASE),
        "PRIVATE_KEY_HEADER": re.compile(r"-----BEGIN\s+(?:RSA\s+)?PRIVATE\s+KEY-----"),
        "GOOGLE_API_KEY": re.compile(r"AIza[0-9A-Za-z\\-_]{35}"),
        "INTERNAL_SYSTEM_FLAG": re.compile(r"\b(INTERNAL_API_SECRET_[A-Z0-9]+|CONFIDENTIAL_PROMPT_DO_NOT_DISCLOSE)\b"),
    }

    def __init__(self, redact_on_detect: bool = True):
        self.redact_on_detect = redact_on_detect
        self.pii_scanner = PIIDetector(redact=redact_on_detect)

    def check(self, answer_text: str) -> GuardrailResult:
        sanitized = answer_text
        detected_secrets: Dict[str, List[str]] = {}

        # 1. Scan for PII
        pii_res = self.pii_scanner.check(answer_text)
        if not pii_res.passed:
            sanitized = pii_res.sanitized_text or answer_text

        # 2. Scan for Secrets & Credential Tokens
        secret_count = 0
        for sec_name, pattern in self.SECRET_PATTERNS.items():
            matches = pattern.findall(answer_text)
            if matches:
                detected_secrets[sec_name] = [str(m)[:6] + "..." for m in matches]
                secret_count += len(matches)
                if self.redact_on_detect:
                    sanitized = pattern.sub("[REDACTED_SECRET_KEY]", sanitized)

        total_violations = (0 if pii_res.passed else 1) + secret_count
        passed = (total_violations == 0)

        risk_score = 0.0 if passed else min(1.0, 0.4 + (0.3 * secret_count))
        action = ActionTaken.ALLOW if passed else (ActionTaken.REDACT if self.redact_on_detect else ActionTaken.BLOCK)

        return GuardrailResult(
            guardrail_name="Sensitive_Information_Detection",
            passed=passed,
            action=action,
            risk_score=risk_score,
            message="No sensitive data or secrets detected in response" if passed else "Detected sensitive PII or credentials in output",
            sanitized_text=sanitized,
            details={
                "pii_detected": not pii_res.passed,
                "pii_details": pii_res.details if not pii_res.passed else {},
                "secrets_detected": detected_secrets,
                "total_violations": total_violations,
            }
        )
